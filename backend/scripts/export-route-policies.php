<?php

declare(strict_types=1);

/** Export the effective CodeIgniter route registry into an auditable matrix. */

require dirname(__DIR__) . '/tests/bootstrap.php';

$output = dirname(__DIR__, 2) . '/docs/05_Security_Audit_Test/AUTHORIZATION_ROUTE_MATRIX.md';
$baselineFile = dirname(__DIR__) . '/security/authorization-route-baseline.json';
$verbs = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'HEAD', 'CLI', '*'];
$routes = service('routes');
$rows = [];

foreach ($verbs as $verb) {
    foreach ($routes->getRoutes($verb, false) as $path => $handler) {
        $options = $routes->getRoutesOptions($path, $verb);
        $filters = normalizeFilters($options['filter'] ?? []);
        $permission = firstFilterValue($filters, 'permission:');
        $ownership = firstFilterValue($filters, 'ownership:');
        $importPermission = in_array('importpermission', $filters, true);
        $superAdmin = in_array('superadmin', $filters, true);
        $feature = firstFilterValue($filters, 'feature:');
        $auth = authPolicy($filters);
        $protected = $auth !== 'PUBLIC';
        $policy = $superAdmin
            ? 'super administrator'
            : ($permission !== ''
            ? $permission
            : ($importPermission
                ? 'resource bulk-import permission'
                : ($ownership !== ''
                ? $ownership . ' ownership'
                : ($auth === 'CANDIDATE_JWT' ? 'candidate ownership' : ($protected ? 'UNDECLARED' : 'public contract')))));

        $rows[] = [
            'method' => $verb,
            'path' => '/' . ltrim((string) $path, '/'),
            'handler' => handlerName($handler),
            'auth' => $auth,
            'permission' => $policy,
            'feature' => $feature !== '' ? $feature : '—',
            'tenant_scope' => tenantScope($auth),
            'status' => $protected && $policy === 'UNDECLARED' ? 'MISSING' : 'DECLARED',
        ];
    }
}

usort($rows, static fn (array $a, array $b): int => [$a['path'], $a['method']] <=> [$b['path'], $b['method']]);
$missing = array_values(array_filter($rows, static fn (array $row): bool => $row['status'] === 'MISSING'));

$markdown = "# Authorization Route Matrix\n\n";
$markdown .= '> Generated by `composer route:matrix`. Do not edit manually.' . "\n\n";
$markdown .= sprintf(
    "Generated: %s  \nRoutes: %d  \nProtected routes without a declared route-level policy: %d\n\n",
    date(DATE_ATOM),
    count($rows),
    count($missing)
);
$markdown .= "`UNDECLARED` means JWT authentication exists but authorization is still implicit/ad-hoc; it is tracked as a gap, not accepted as secure.\n\n";
$markdown .= "| Method | Route | Handler | Auth | Permission/policy | Feature | Tenant scope | Status |\n";
$markdown .= "|---|---|---|---|---|---|---|---|\n";
foreach ($rows as $row) {
    $markdown .= '| ' . implode(' | ', array_map('escapeCell', $row)) . " |\n";
}

$directory = dirname($output);
if (! is_dir($directory)) {
    mkdir($directory, 0750, true);
}
file_put_contents($output, $markdown);

$missingFingerprints = array_values(array_map('routeFingerprint', $missing));
sort($missingFingerprints);
if (in_array('--update-baseline', $argv, true)) {
    file_put_contents($baselineFile, json_encode([
        'version' => 1,
        'description' => 'Acknowledged legacy JWT routes without a declared route-level authorization policy.',
        'fingerprints' => $missingFingerprints,
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . PHP_EOL);
}

fwrite(STDOUT, sprintf(
    "Route matrix written: %d routes, %d protected routes missing declared policy.\n%s\n",
    count($rows),
    count($missing),
    $output
));

if (in_array('--strict', $argv, true)) {
    $baseline = is_file($baselineFile) ? json_decode((string) file_get_contents($baselineFile), true) : null;
    if (! is_array($baseline) || ! is_array($baseline['fingerprints'] ?? null)) {
        fwrite(STDERR, "Authorization route baseline is missing or invalid: {$baselineFile}\n");
        exit(1);
    }
    $new = array_values(array_diff($missingFingerprints, $baseline['fingerprints']));
    if ($new !== []) {
        fwrite(STDERR, "New protected routes without a declared authorization policy:\n  - " . implode("\n  - ", $new) . "\n");
        exit(1);
    }
}

function routeFingerprint(array $row): string
{
    return $row['method'] . ' ' . $row['path'] . ' -> ' . $row['handler'];
}

function normalizeFilters(mixed $filters): array
{
    if (is_string($filters)) {
        return array_values(array_filter(array_map('trim', explode(',', $filters))));
    }
    if (! is_array($filters)) {
        return [];
    }
    $result = [];
    array_walk_recursive($filters, static function (mixed $filter) use (&$result): void {
        if (is_string($filter) && trim($filter) !== '') {
            $result[] = trim($filter);
        }
    });
    return $result;
}

function firstFilterValue(array $filters, string $prefix): string
{
    foreach ($filters as $filter) {
        if (str_starts_with($filter, $prefix)) {
            return substr($filter, strlen($prefix));
        }
    }
    return '';
}

function authPolicy(array $filters): string
{
    foreach ($filters as $filter) {
        $name = strtolower(strtok($filter, ':'));
        if (in_array($name, ['jwt', 'jwt-auth'], true)) {
            return 'JWT';
        }
        if (in_array($name, ['candidatejwt', 'candidate-jwt'], true)) {
            return 'CANDIDATE_JWT';
        }
        if (in_array($name, ['api-key', 'apikey'], true)) {
            return 'API_KEY';
        }
    }
    return 'PUBLIC';
}

function tenantScope(string $auth): string
{
    return match ($auth) {
        'JWT' => 'active company',
        'CANDIDATE_JWT' => 'candidate company',
        'API_KEY' => 'API key company',
        default => 'public/provider/signed contract',
    };
}

function handlerName(mixed $handler): string
{
    if (is_string($handler)) {
        return $handler;
    }
    if ($handler instanceof Closure) {
        return 'Closure';
    }
    return get_debug_type($handler);
}

function escapeCell(mixed $value): string
{
    return str_replace(['|', "\r", "\n"], ['\\|', ' ', ' '], (string) $value);
}
